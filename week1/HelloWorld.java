// This is a single-line comment. The compiler ignores it.
/*
 * This is a multi-line comment.
 * It can span multiple lines.
 */
// public: accessible from anywhere. class: defines a class.
// HelloWorld: the class name (must match the file name).
public class HelloWorld {
    // static: belongs to the class. void: returns nothing.
    // main: entry point. String[] args: command-line arguments.
    public static void main(String[] args) {
        // println prints a line; the text in quotes is a string literal.
        System.out.println("Hello, World!");
        System.out.println("My name is: Brian Muinde");
        System.out.println("I am learning Java at Riara University");
        System.out.println("Today's date is: 2026-11-03");
    }
}
